/** Нормализация строки поиска: нижний регистр, ё→е, без лишних пробелов. */
export function normalizeCityQuery(s: string): string {
  return s.toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim()
}

export interface SearchHit {
  id: string
  name: string
  country: string
  lat: number
  lon: number
  source: 'local' | 'api'
}

let localIdSeq = 0

/** Локальный нечёткий поиск: совпадение с начала слова > включение, ранжирование по населению. */
export function searchLocalCities(query: string, limit = 6): SearchHit[] {
  const q = normalizeCityQuery(query)
  if (q.length < 2) return []
  const scored: Array<{ hit: SearchHit; score: number }> = []
  for (const c of CITIES) {
    const n = normalizeCityQuery(c.name)
    const a = c.alt ? normalizeCityQuery(c.alt) : ''
    let score = -1
    if (n === q) score = 100
    else if (n.startsWith(q)) score = 80 - n.length * 0.1
    else if (a && a.startsWith(q)) score = 70
    else if (n.split(' ').some((w) => w.startsWith(q))) score = 60
    else if (n.includes(q)) score = 40
    else if (a && a.includes(q)) score = 30
    if (score < 0) continue
    score += Math.min(c.pop / 1000, 20) // лёгкий буст по населению
    scored.push({
      hit: {
        id: `local-${localIdSeq++}-${c.lat.toFixed(2)}_${c.lon.toFixed(2)}`,
        name: c.name,
        country: c.country,
        lat: c.lat,
        lon: c.lon,
        source: 'local',
      },
      score,
    })
  }
  scored.sort((x, y) => y.score - x.score)
  return scored.slice(0, limit).map((s) => s.hit)
}
